// поиск: совпадение по имени или ключевым словам, без регистра
function search(query, cat) {
    const q = query.trim().toLowerCase()
    const out = []

    for (var i = 0; i < emoji.length; i++) {
        const e = emoji[i]

        if (cat !== "" && cat !== undefined && cat !== null
                && e.cat !== cat)
            continue

        if (q === ""
                || e.name.toLowerCase().indexOf(q) !== -1
                || e.kw.toLowerCase().indexOf(q) !== -1) {
            out.push(e)
        }
    }

    return out
}

function byCategory(cat) {
    return search("", cat)
}

// индекс по символу для имён недавних (ленивый)
var _charIndex = null

function nameOf(ch) {
    if (_charIndex === null) {
        _charIndex = {}

        for (var i = 0; i < emoji.length; i++)
            _charIndex[emoji[i].ch] = emoji[i]
    }

    return _charIndex[ch] ? _charIndex[ch].name : ""
}

function infoOf(ch) {
    if (_charIndex === null) {
        _charIndex = {}

        for (var i = 0; i < emoji.length; i++)
            _charIndex[emoji[i].ch] = emoji[i]
    }

    return _charIndex[ch] || null
}
